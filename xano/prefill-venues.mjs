#!/usr/bin/env node
/**
 * Разовий прифіл домашньої арени клубів: `TeamInfo.home_venues_id` з матчів.
 *
 *   node xano/prefill-venues.mjs           — нічого не пише, друкує план
 *   node xano/prefill-venues.mjs --apply   — записує
 *
 * Звідки береться значення: серед матчів, де клуб господар
 * (`Match.team1_id` = клуб) і заповнене `Match.venues_id`, береться найчастіша
 * арена. Обґрунтування й розклад по клубах — `docs/proposals/crm-club-fields.md`
 * розділ 6 у репозиторії AFU.
 *
 * Правила (звідти ж, 6.3):
 * - пишемо ЛИШЕ в порожнє: заповнене руками значення не чіпаємо ніколи;
 * - клуби без домашніх матчів не чіпаємо взагалі — ні нулем, ні порожнім;
 * - слабка підстава (≤3 домашніх матчів) не блокує запис, але йде окремим
 *   списком: 100 % на двох матчах — це не 100 %;
 * - повторний прогін без нових матчів не змінює жодного рядка.
 *
 * Приклад виводу (--check, 15.09.2026):
 *   52 клуби пропущено (немає домашніх матчів або вже заповнено)
 *   ~ 43 СкайАп → 8 «м. Київ, GYMMAXX» (95 %, 19 матчів)
 *   слабкі: 60 Фантом (2 матчі), 61 Агромат (3), 62 Альянс (1)
 */
import { мета } from './meta.mjs';

const ЗАСТОСУВАТИ = process.argv.includes('--apply');
const СЛАБКО = 3; // домашніх матчів, за яких частка ще нічого не доводить

const сторінками = async (шлях) => {
  const усе = [];
  for (let page = 1; page <= 20; page++) {
    const r = await мета('GET', `${шлях}?per_page=500&page=${page}`);
    const рядки = r.items ?? r;
    усе.push(...рядки);
    if (рядки.length < 500) break;
  }
  return усе;
};

const матчі = await сторінками('/workspace/1/table/1/content');
const клуби = await сторінками('/workspace/1/table/4/content');
const арени = Object.fromEntries((await сторінками('/workspace/1/table/2/content')).map((v) => [v.id, v.City]));

const план = [];
const слабкі = [];
let пропущено = 0;

for (const клуб of клуби) {
  // Заповнене руками важливіше за порахане: інакше ручна правка зникне
  // при наступному прогоні, і ніхто не помітить, бо поле знову «має значення».
  if (клуб.home_venues_id) {
    пропущено++;
    continue;
  }
  const дома = матчі.filter((m) => m.team1_id === клуб.id && m.venues_id);
  if (!дома.length) {
    пропущено++;
    continue;
  }
  const скільки = {};
  for (const m of дома) скільки[m.venues_id] = (скільки[m.venues_id] ?? 0) + 1;
  const [арена, n] = Object.entries(скільки).sort((a, b) => b[1] - a[1])[0];
  const рядок = {
    id: клуб.id,
    назва: клуб.TeamName,
    арена: Number(арена),
    підпис: арени[арена] ?? `#${арена}`,
    частка: n / дома.length,
    матчів: дома.length,
  };
  план.push(рядок);
  if (дома.length <= СЛАБКО) слабкі.push(рядок);
}

for (const р of план) {
  console.log(
    `~ ${String(р.id).padStart(3)} ${String(р.назва).padEnd(24)} → ${String(р.арена).padStart(2)} «${р.підпис}» ` +
      `(${(р.частка * 100).toFixed(0)} %, ${р.матчів} матчів)`
  );
  if (ЗАСТОСУВАТИ) await мета('PUT', `/workspace/1/table/4/content/${р.id}`, { home_venues_id: р.арена });
}

console.log(`\n${пропущено} клубів пропущено (немає домашніх матчів або вже заповнено)`);
console.log(`${план.length} ${ЗАСТОСУВАТИ ? 'записано' : 'до запису'}`);
if (слабкі.length) {
  console.log(
    `слабка підстава (≤${СЛАБКО} матчів), підтвердити руками: ` +
      слабкі.map((р) => `${р.id} ${р.назва} (${р.матчів})`).join(', ')
  );
}
if (!ЗАСТОСУВАТИ) console.log('\n[перевірка] нічого не записано; запис — з --apply');
