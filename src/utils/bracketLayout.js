/**
 * Розкладка сітки плей-оф деревом: колонки раундів і окремо «За 3 місце».
 *
 * ЗВІДКИ ДАНІ. `bracket/byligid/stage_id/allInfo` віддає `tours` (раунди в
 * порядку турніру) і `bracket` — пари. Пара це СЕРІЯ: `teaminfo_id1/2`,
 * рахунок серії `result_team1/2` і матчі в `_matchlist_by_tours_id`. Номера
 * місця в сітці сервер не дає (`match_number` порожній), тож хто з ким
 * зʼєднаний дужкою, виводимо самі — з того, хто куди пройшов.
 *
 * ПОРЯДОК — ВІД ФІНАЛУ НАЗАД. Пара наступного раунду в слоті j зводить
 * переможців слотів 2j і 2j+1 попереднього. Тож ставимо фінал, а під кожну
 * його команду шукаємо пару, де вона грала раундом раніше, і так до першого
 * раунду. На живих даних 2024/25 сервер і так віддає пари в цьому порядку,
 * але покладатися на це — значить намалювати дужку між чужими парами, щойно
 * в CRM переставлять рядки. Пара, якої не вдалося привʼязати (раунд ще не
 * зведено), стає у вільний слот у серверному порядку.
 *
 * «ЗА 3 МІСЦЕ» — НЕ КОЛОНКА. Назва раунду довільна («За 3 місце» у 2024/25,
 * «Бронзова серія» у 2025/26), тож розпізнаємо за даними: обидві команди
 * пари програли в попередньому раунді. Коли пар іще немає — за назвою, бо
 * більше нема за чим.
 *
 * Чиста функція без React: її перевіряють тести, а компонент лише малює.
 */

/** Етап типу «сітка» — це плей-оф. Назву не розбираємо: вона довільна. */
export const isBracketStage = stage =>
  String(stage?.league_stage_type ?? '').toLowerCase() === 'сітка';

/*
  Тур без пар — «За 3 місце» лише за справжнім позначенням: «за 3…»,
  «за третє…», «3 місце», «третє місце», «бронз…». Не «трет» узагалі:
  «Третій попередній етап» Кубка 2026/27 виносився блоком після фіналу
  (PM 2, 14.11). Порожній тур з номером («3 тур», «Тур 3») — теж колонка.
*/
const ЗА_ТРЕТЄ_НАЗВА =
  /(за\s+(3|трет)|(^|[^\d])3(-?т?[єе])?\s+місц|трет[єе]\s+місц|бронз)/i;

const команди = пара => [пара?.teaminfo_id1, пара?.teaminfo_id2];

/**
 * Кубкова пара з двох матчів (бриф cup-two-leg-ties, чат АФУ 09.11; як у
 * Flashscore): `kind: 'two_leg'` і матчі в `legs` (порядок — за часом;
 * score/penalty — в орієнтації пари [teaminfo_id1, teaminfo_id2]). Для
 * `series` (до 2–3 перемог), `single` і пар без цих полів — як досі.
 */
export const двоматчева = пара =>
  пара?.kind === 'two_leg' && Array.isArray(пара?.legs) && пара.legs.length > 0;

const пара2 = значення =>
  Array.isArray(значення) &&
  значення.length === 2 &&
  значення.every(n => n !== null && n !== '' && Number.isFinite(Number(n)))
    ? значення.map(Number)
    : null;

/** Серія пенальті після другого матчу пари: [a, b] або null. */
export const серіяПари = пара => {
  const legs = Array.isArray(пара?.legs) ? пара.legs : [];
  return пара2(legs[legs.length - 1]?.penalty);
};

/**
 * Хто пройшов: для пари з двох матчів — `winner_teaminfo_id` від сервера,
 * а без нього — за сумою м'ячів `aggregate` (основний час + екстра-тайми,
 * без серії), за рівної — за серією після другого матчу; для серії плей-оф
 * і `single` — за `result_team1/2`, як досі. `null`, доки не вирішено.
 */
export const переможецьСерії = пара => {
  if (двоматчева(пара)) {
    // Сервер знає, чи зіграно обидва матчі (docs/xano/cup-two-leg-contract.md):
    // його winner_teaminfo_id важливіший; власний розрахунок — лише без поля.
    if (пара.winner_teaminfo_id !== undefined) {
      return пара.winner_teaminfo_id ?? null;
    }
    const сума = пара2(пара.aggregate);
    if (!сума) {
      return null;
    }
    let [х, у] = сума;
    if (х === у) {
      const серія = серіяПари(пара);
      if (!серія || серія[0] === серія[1]) {
        return null;
      }
      [х, у] = серія;
    }
    return х > у ? пара.teaminfo_id1 : пара.teaminfo_id2;
  }
  const а = Number(пара?.result_team1);
  const б = Number(пара?.result_team2);
  if (!Number.isFinite(а) || !Number.isFinite(б) || а === б) {
    return null;
  }
  return а > б ? пара.teaminfo_id1 : пара.teaminfo_id2;
};

const програвшіРаунду = пари =>
  пари
    .map(пара => {
      const переможець = переможецьСерії(пара);
      if (переможець == null) {
        return null;
      }
      return переможець === пара.teaminfo_id1
        ? пара.teaminfo_id2
        : пара.teaminfo_id1;
    })
    .filter(id => id != null);

/*
  Попередній раунд — не обовʼязково сусідній: у 2024/25 «За 3 місце» йде
  ПІСЛЯ фіналу, тож програвших шукаємо в будь-якому раунді, де пар не менше
  двох, — обидві команди мають вилетіти саме в ньому.
*/
const цеЗаТретє = (тур, пари, основні) => {
  if (пари.length === 1) {
    return основні.some(раунд => {
      if (раунд.пари.length < 2) {
        return false;
      }
      const програвші = програвшіРаунду(раунд.пари);
      return команди(пари[0]).every(id => id != null && програвші.includes(id));
    });
  }
  if (пари.length === 0) {
    return ЗА_ТРЕТЄ_НАЗВА.test(String(тур?.TourName ?? ''));
  }
  return false;
};

/**
 * @returns {{
 *   колонки: { id, назва, пари: (object|null)[] }[],
 *   заТретє: { id, назва, пара: object|null } | null,
 *   порожня: boolean,
 * }}
 */
export const розкластиСітку = ({ tours, bracket } = {}) => {
  const тури = Array.isArray(tours) ? tours : [];
  const усіПари = Array.isArray(bracket) ? bracket : [];

  const паримРаунду = id => усіПари.filter(пара => пара?.tours_id === id);

  // Тури, у яких є пари, але сервер про них не сказав, — у кінець, щоб пара
  // не зникла мовчки.
  const відомі = new Set(тури.map(тур => тур?.id));
  const сироти = [
    ...new Set(
      усіПари.map(пара => пара?.tours_id).filter(id => !відомі.has(id))
    ),
  ].map(id => ({ id, TourName: 'Раунд' }));

  let заТретє = null;
  const основні = [];
  [...тури, ...сироти].forEach(тур => {
    const пари = паримРаунду(тур?.id);
    if (!заТретє && цеЗаТретє(тур, пари, основні)) {
      заТретє = {
        id: тур.id,
        назва: тур.TourName ?? '',
        пара: пари[0] ?? null,
      };
      return;
    }
    основні.push({ id: тур?.id, назва: тур?.TourName ?? '', пари });
  });

  if (основні.length === 0) {
    return { колонки: [], заТретє, порожня: !заТретє?.пара };
  }

  // Слотів у раунді вдвічі більше, ніж у наступному, але не менше, ніж пар.
  const слоти = основні.map(к => к.пари.length);
  слоти[слоти.length - 1] = Math.max(1, слоти[слоти.length - 1]);
  for (let к = слоти.length - 2; к >= 0; к -= 1) {
    слоти[к] = Math.max(слоти[к], слоти[к + 1] * 2);
  }

  const колонки = основні.map((к, і) => ({
    id: к.id,
    назва: к.назва,
    пари: Array(слоти[і]).fill(null),
  }));

  const останній = колонки.length - 1;
  основні[останній].пари.forEach((пара, j) => {
    колонки[останній].пари[j] = пара;
  });

  for (let к = останній - 1; к >= 0; к -= 1) {
    const вільні = [...основні[к].пари];
    const взяти = id => {
      if (id == null) {
        return null;
      }
      const і = вільні.findIndex(пара => команди(пара).includes(id));
      return і === -1 ? null : вільні.splice(і, 1)[0];
    };

    колонки[к + 1].пари.forEach((наступна, j) => {
      if (наступна) {
        колонки[к].пари[2 * j] = взяти(наступна.teaminfo_id1);
        колонки[к].пари[2 * j + 1] = взяти(наступна.teaminfo_id2);
      }
    });

    вільні.forEach(пара => {
      const слот = колонки[к].пари.indexOf(null);
      if (слот !== -1) {
        колонки[к].пари[слот] = пара;
      }
    });
  }

  const порожня =
    колонки.every(к => к.пари.every(пара => пара == null)) && !заТретє?.пара;

  return { колонки, заТретє, порожня };
};
