// Стиснення зображень у браузері перед завантаженням.
//
// НАВІЩО. Люди вантажать фото прямо з телефона: 4–10 МБ, 4000 px по довшій
// стороні. Сайт і застосунок показують їх у кращому разі на пів екрана, а
// тягнуть цілком — і в базі вже лежать такі (2830×4164). Тому зменшуємо до
// розумної сторони й перекодовуємо ще до відправки: менше чекати на
// завантаження, менше важить кожен показ.
//
// ЧОГО НЕ РОБИМО:
//   - не збільшуємо: менше за межу лишається свого розміру;
//   - не перекодовуємо легке: файл, що вже в межі й важить небагато, іде як є —
//     кожне перекодування JPEG трохи псує картинку, а виграшу тут нема;
//   - не віддаємо результат, важчий за оригінал того самого розміру;
//   - не чіпаємо SVG і GIF: перше векторне, друге може бути анімоване.
//
// ОРІЄНТАЦІЯ. Телефон пише кадр «боком» і кладе поворот в EXIF. Канвас EXIF не
// переносить, тож повертати треба при декодуванні: createImageBitmap з
// imageOrientation: 'from-image'. Де його нема — <img>, який сучасні браузери
// повертають за EXIF самі. На виході поворот уже «впечений» у пікселі.
//
// Приклад:
//   вхід:  File 'IMG_0412.HEIC.jpg', 6,8 МБ, 4032×3024
//   вихід: { file: File 'IMG_0412.HEIC.jpg' image/jpeg ~350 КБ 1600×1200,
//            було: 7130000, стало: 358000, перекодовано: true }
//   опис:  '6,8 МБ → 350 КБ'

// Фото для показу на сайті й у застосунку: новини, фото команди, організація
// матчу, керівні органи. 1600 — з запасом на ретину при ширині ~800 px.
export const ФОТО = {
  максСторона: 1600,
  якість: 0.85,
  легкий: 500 * 1024,
  прозорість: false,
};

// Логотипи, що йдуть без кадрування (партнери): прозорість зберігаємо, тож PNG
// лишається PNG. Показуються дрібно, 1000 px — більш ніж досить.
export const ЛОГО = {
  максСторона: 1000,
  якість: 0.85,
  легкий: 300 * 1024,
  прозорість: true,
};

// Кадрований квадрат фото людини (PhotoCropper). Раніше 0.92. Звірено 14.10 на
// кадрі 600 px із дрібним друкованим текстом — найгіршому для JPEG: на око
// різниці нема навіть у збільшенні, файл легший на п'яту частину (200 → 159 КБ).
export const ЯКІСТЬ_КАДРУ = 0.85;

const НЕ_ЧІПАТИ = ['image/svg+xml', 'image/gif'];
const З_ПРОЗОРІСТЮ = ['image/png', 'image/webp'];

/** Розмір після зменшення. k ≤ 1: збільшення не буває. */
export function цільовийРозмір(ширина, висота, максСторона) {
  const k = Math.min(1, максСторона / Math.max(ширина, висота));
  return { ширина: Math.max(1, Math.round(ширина * k)), висота: Math.max(1, Math.round(висота * k)), k };
}

/** PNG лише там, де прозорість потрібна і вона в джерелі можлива. */
export function вихіднийТип(типДжерела, прозорість) {
  return прозорість && З_ПРОЗОРІСТЮ.includes(типДжерела) ? 'image/png' : 'image/jpeg';
}

function імʼяДля(name, тип) {
  const база = String(name || 'image').replace(/\.[^.]+$/, '');
  return `${база}.${тип === 'image/png' ? 'png' : 'jpg'}`;
}

const браузерні = {
  async декодувати(file) {
    if (typeof createImageBitmap === 'function') {
      try {
        const b = await createImageBitmap(file, { imageOrientation: 'from-image' });
        return { ширина: b.width, висота: b.height, джерело: b, закрити: () => b.close?.() };
      } catch {
        // Safari старших версій не знає опцій — падаємо на <img>
      }
    }
    const url = URL.createObjectURL(file);
    try {
      const img = await new Promise((готово, зле) => {
        const i = new Image();
        i.onload = () => готово(i);
        i.onerror = () => зле(new Error('не вдалося прочитати зображення'));
        i.src = url;
      });
      return { ширина: img.naturalWidth, висота: img.naturalHeight, джерело: img, закрити: () => {} };
    } finally {
      URL.revokeObjectURL(url);
    }
  },
  async закодувати(джерело, ширина, висота, тип, якість) {
    const c = document.createElement('canvas');
    c.width = ширина;
    c.height = висота;
    const ctx = c.getContext('2d');
    if (тип === 'image/jpeg') {
      // JPEG прозорості не має: прозоре стало б чорним
      ctx.fillStyle = '#fff';
      ctx.fillRect(0, 0, ширина, висота);
    }
    ctx.imageSmoothingQuality = 'high';
    ctx.drawImage(джерело, 0, 0, ширина, висота);
    const blob = await new Promise((r) => c.toBlob(r, тип, якість));
    if (!blob) throw new Error('не вдалося стиснути зображення');
    return blob;
  },
};

/**
 * Стиснути файл зображення. Ніколи не кидає через саме стиснення: якщо щось
 * пішло не так, повертає оригінал — краще важке фото, ніж незавантажене.
 */
export async function стиснутиФото(file, опції = ФОТО, засоби = браузерні) {
  const { максСторона, якість, легкий, прозорість } = { ...ФОТО, ...опції };
  const як_є = { file, було: file?.size || 0, стало: file?.size || 0, перекодовано: false };
  if (!file || !String(file.type).startsWith('image/') || НЕ_ЧІПАТИ.includes(file.type)) return як_є;

  let д;
  try {
    д = await засоби.декодувати(file);
  } catch {
    return як_є;
  }
  try {
    const ц = цільовийРозмір(д.ширина, д.висота, максСторона);
    if (ц.k === 1 && file.size <= легкий) return { ...як_є, ширина: д.ширина, висота: д.висота };

    const тип = вихіднийТип(file.type, прозорість);
    const blob = await засоби.закодувати(д.джерело, ц.ширина, ц.висота, тип, якість);
    // Того самого розміру, але важче — перекодування нічого не дало
    if (ц.k === 1 && blob.size >= file.size) return { ...як_є, ширина: д.ширина, висота: д.висота };

    const новий = new File([blob], імʼяДля(file.name, тип), { type: тип, lastModified: Date.now() });
    return { file: новий, було: file.size, стало: новий.size, перекодовано: true, ширина: ц.ширина, висота: ц.висота };
  } catch {
    return як_є;
  } finally {
    д.закрити();
  }
}

/** '6,8 МБ', '350 КБ' */
export function розмірФайлу(байти) {
  if (байти >= 1024 * 1024) return `${(байти / 1024 / 1024).toFixed(1).replace('.', ',')} МБ`;
  return `${Math.max(1, Math.round(байти / 1024))} КБ`;
}

/** '6,8 МБ → 350 КБ' або null, якщо файл пішов як є. */
export function описСтиснення(r) {
  if (!r?.перекодовано) return null;
  return `${розмірФайлу(r.було)} → ${розмірФайлу(r.стало)}`;
}
