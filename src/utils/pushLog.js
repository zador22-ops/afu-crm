// Журнал пушів (push_log) на сторінці «Пуші»: розсилки окремо, збої окремо.
//
// Збої сповіщень гри Backend пише в той самий push_log (docs/xano/game-api.md
// у репо AFU, «Для CRM», 19.10): kind = game_error, mode = error, recipients 0,
// title — джерело (game_hourly чи game/finish), body — коротке повідомлення без
// токенів і пошт. Це не розсилка, тож у журналі відправлень їй не місце: там
// вона виглядала б як «пуш нікому».
//
// Обмеження: сервер віддає останні 100 рядків журналу разом (push-templates
// GET), тож збій, старший за 100 записів, сюди вже не потрапить. Зараз це
// тижні; якщо розсилок стане багато — збої треба віддавати з сервера окремо.

export const чиЗбій = (r) => r?.kind === 'game_error' || r?.mode === 'error';

/** { збої, розсилки } — порядок усередині кожної частини той самий, що прийшов. */
export function розділитиЖурнал(log) {
  const збої = [];
  const розсилки = [];
  for (const r of Array.isArray(log) ? log : []) (чиЗбій(r) ? збої : розсилки).push(r);
  return { збої, розсилки };
}

const ДЖЕРЕЛА = {
  game_hourly: 'щогодинна задача гри',
  'game/finish': 'кінець партії',
};

/** Людська назва джерела збою; невідоме — як є. */
export const джерелоЗбою = (title) => ДЖЕРЕЛА[title] || title || '—';
