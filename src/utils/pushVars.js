export const чиГра = (kind) => String(kind || '').startsWith('game_');

/** Набір змінних і приклад для пуша цього виду. */
export function змінніДля(kind) {
  return чиГра(kind) ? { змінні: ЗМІННІ_ГРИ[kind] || {}, приклад: ПРИКЛАД_ГРИ } : { змінні: ЗМІННІ_МАТЧУ, приклад: ПРИКЛАД_МАТЧУ };
}

/** Змінні з тексту, яких цей вид пуша не знає. */
export function невідоміЗмінні(тексти, kind) {
  const { змінні } = змінніДля(kind);
  return тексти.flatMap((s) => [...String(s || '').matchAll(/\{(\w*)\}/g)].map((m) => m[1])).filter((k) => !(k in змінні));
}

export const заповнити = (шаблон, vars = ПРИКЛАД_МАТЧУ) =>
  String(шаблон || '')
    .replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : String(vars[k])))
    .replace(/\(\s*\)/g, '')
    .replace(/\s+,/g, ',')
    .replace(/,\s*(?=·|$)/g, '')
    .replace(/·\s*(?=·|$)/g, '')
    .replace(/^\s*·\s*/, '')
    .replace(/\s{2,}/g, ' ')
    .trim();
