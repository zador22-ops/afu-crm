// Статуси матчу, які міняються з причиною: «Перенесений» (2) і «Призупинено»
// (5). Брифи match-postpone-after-start і match-pause-and-note, слово Андрія
// 19.10. Сервер:
//   POST crm/matches/{id}/postpone — 3/4/5 → 2;
//   POST crm/matches/{id}/pause    — 3 → 5;
//   POST crm/matches/{id}/result   — 5 → 3 («Відновити») чи 4 («Завершити»);
//   PATCH crm/matches/{id}         — 1 → 2 у картці розкладу, з reason.
// Причина йде в Match.status_note — її бачать уболівальники, поки статус 2
// чи 5 — і з датою в коментар матчу. Перенесений матч зникає з таблиці,
// призупинений лишається з рахунком на момент паузи. Статистику гравців не
// чіпає жоден перехід (слово Андрія 19.10).
//
// Ті самі умови перевіряє сервер (xano/crm/matches-id-*.xs) — тут вони лише
// для того, щоб кнопки й форми не пропонували марного.

export const ПЕРЕНЕСЕНИЙ = 2;
export const ОНЛАЙН = 3;
export const ПРИЗУПИНЕНО = 5;

export const ПРИЧИНА_МІН = 3;

export const ПОПЕРЕДЖЕННЯ =
  'Матч зникне з турнірної таблиці. Події протоколу залишаться, але в таблицю не йдуть, доки матч не зіграють.';

export const ПОПЕРЕДЖЕННЯ_ПАУЗИ =
  'Матч лишиться в турнірній таблиці з рахунком на момент паузи. Далі — «Відновити матч», «Зіграний» або «Перенести матч».';

export const ПУБЛІЧНА = 'Причину побачать уболівальники в застосунку — без персональних даних';

// Готові причини одним натиском (бриф: «Повітряна тривога» — кнопка-підказка)
export const ПІДКАЗКИ_ПАУЗИ = ['Повітряна тривога'];

const статус = (s) => Number(s);

/** «Перенести матч» на сторінці матчу: «Онлайн», «Зіграний», «Призупинено». */
export const можнаПеренести = (s) => [3, 4, 5].includes(статус(s));
export const можнаПризупинити = (s) => статус(s) === ОНЛАЙН;
export const можнаВідновити = (s) => статус(s) === ПРИЗУПИНЕНО;

/** Чи є в цьому статусі причина для вболівальників (status_note). */
export const зПричиною = (s) => [ПЕРЕНЕСЕНИЙ, ПРИЗУПИНЕНО].includes(статус(s));

/** Картка розкладу: перехід у «Перенесений» з іншого статусу — потрібна причина. */
export const потрібнаПричина = (було, стане) => статус(стане) === ПЕРЕНЕСЕНИЙ && статус(було) !== ПЕРЕНЕСЕНИЙ;

export const причинаГодиться = (text) => String(text || '').trim().length >= ПРИЧИНА_МІН;
