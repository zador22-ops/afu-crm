// «Перенести матч» для «Онлайн» чи «Зіграного» (бриф match-postpone-after-start,
// слово Андрія 19.10). Сервер — POST crm/matches/{id}/postpone: статус 2,
// причина дописується в коментар матчу, рядки таблиці прибираються, пуш
// «Матч перенесено». Події протоколу лишаються, але поки матч перенесений,
// у таблицю й статистику не йдуть.
//
// Ті самі умови перевіряє сервер (xano/crm/matches-id-postpone.post.xs) —
// тут вони лише для того, щоб кнопка й форма не пропонували марного.

export const ПРИЧИНА_МІН = 3;

export const ПОПЕРЕДЖЕННЯ =
  'Матч зникне з турнірної таблиці. Події протоколу залишаться, але не рахуватимуться, доки матч не зіграють.';

/** Переносити звідси можна лише «Онлайн» (3) і «Зіграний» (4). */
export const можнаПеренести = (status) => [3, 4].includes(Number(status));

export const причинаГодиться = (text) => String(text || '').trim().length >= ПРИЧИНА_МІН;
