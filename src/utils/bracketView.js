//
// Дерево малюємо з тих самих даних і тією самою розкладкою, що й застосунок:
//   дані      — публічний Default `bracket/byStage/allInfo` (рахунок серії, пари з двох матчів, переможець);
//   розкладка — `розкластиСітку` з ./bracketLayout.js, дослівна копія AFU utils/bracketLayout.js (тест звіряє).
// Список турів і учасників для редагування — як і раніше, з crm `tournaments/{id}/bracket` і `participants`.

/** Етапи типу «сітка» турніру з їхніми раундами, у порядку турів. */
export function стадіїСітки(tours) {
  const стадії = new Map();
  for (const т of tours || []) {
    if (т?._stage?.stage_type !== 'сітка') continue;
    const id = т.league_stage_id;
    if (!стадії.has(id)) стадії.set(id, { id, назва: т._stage.stage_name || 'Плей-оф', раунди: [] });
    стадії.get(id).раунди.push(т);
  }
  return [...стадії.values()];
}

const зіграний = (м) => Number(м?.match_status_id) === 4;

/**
 * Рядок стану пари під командами: чи є матчі й чи зіграні. Рахунок картка показує сама (як у застосунку),
 * тож тут — лише те, чого з рахунку не видно. null — усе зіграно, підпис не потрібен.
 */
export function станПари(пара) {
  // Бай: суперника немає навмисно, матчу в цьому раунді не буде (бриф bracket-bye)
  if (пара && !єСуперник(пара)) return 'без матчу (бай)';
  const матчі = Array.isArray(пара?.legs) ? пара.legs : [];
  if (!матчі.length) return 'матчу ще немає';
  const зіграно = матчі.filter(зіграний).length;
  if (зіграно === матчі.length) return null;
  if (матчі.length === 1) return 'матч призначено, не зіграний';
  return `зіграно ${зіграно} з ${матчі.length}`;
}

/** Рахунок одного матчу пари в орієнтації пари [команда 1, команда 2], серія пенальті окремо. */
export function рахунокМатчу(матч) {
  if (!зіграний(матч) || !Array.isArray(матч?.score)) return null;
  const [а, б] = матч.score;
  const серія = Array.isArray(матч.penalty) ? ` (пен. ${матч.penalty[0]}:${матч.penalty[1]})` : '';
  return `${а}:${б}${серія}`;
}

/**
 * Чи вирішує порядок пар (Bracket.position) їхнє місце в колонці k дерева. Так — якщо в наступній колонці
 * немає жодної пари: тоді розкладка ставить пари колонки в серверному порядку. Якщо наступний раунд уже
 * зведено, слоти колонки визначають команди (хто куди пройшов), і пересування нічого не змінить.
 */
export const порядокВирішує = (колонки, к) => !(колонки?.[к + 1]?.пари || []).some(Boolean);

/** Нове місце пари при перетягуванні на іншу пару того ж раунду: місце цілі в серверному порядку туру (1…n). */
export function місцеЦілі(пари, ціль) {
  const тур = (пари || []).filter((п) => п?.tours_id === ціль?.tours_id);
  const і = тур.findIndex((п) => п.id === ціль?.id);
  return і === -1 ? null : і + 1;
}

/** Пересунути пару на крок вище (-1) чи нижче (+1) у серверному порядку туру; null — далі нікуди. */
export function місцеНаКрок(пари, пара, крок) {
  const тур = (пари || []).filter((п) => п?.tours_id === пара?.tours_id);
  const і = тур.findIndex((п) => п.id === пара?.id);
  const нове = і + крок;
  return і === -1 || нове < 0 || нове >= тур.length ? null : нове + 1;
}

// ——— Пара з однією командою: бай / вайлд-кард (бриф bracket-bye 17.11, bracket-bye-team1 19.11) ———
// Команда заходить у раунд без матчу в попередньому: у парі лише одна команда — з будь-якого боку
// (адмін обирає, звідки «очікує суперника»). Повністю порожньої пари не буває.
export const БЕЗ_СУПЕРНИКА = 'Очікує суперника';

/** Чи є в пари команда з боку 1 чи 2: id > 0 (сервер для порожньої віддає null чи 0). */
export const єКоманда = (пара, сторона) => Number(сторона === 1 ? пара?.teaminfo_id1 : пара?.teaminfo_id2) > 0;

/** Повна пара — обидві команди на місці; інакше це бай. */
export const єСуперник = (пара) => єКоманда(пара, 1) && єКоманда(пара, 2);

/** Назва команди пари з боку 1 чи 2; порожній бік — «Очікує суперника». */
export const назваКоманди = (пара, сторона) =>
  єКоманда(пара, сторона) ? (сторона === 1 ? пара?._teaminfo1 : пара?._teaminfo2)?.TeamName || 'Команда' : БЕЗ_СУПЕРНИКА;

/** Форма пари: обидві команди порожні — відправляти не можна. */
export const обидвіПорожні = (v) => !(Number(v?.teaminfo_id1) > 0) && !(Number(v?.teaminfo_id2) > 0);

/** Тіло POST нової пари: порожньої команди в тілі немає взагалі (ключа немає). */
export function тілоНовоїПари(v) {
  const тіло = { tours_id: Number(v.tours_id) };
  if (Number(v.teaminfo_id1) > 0) тіло.teaminfo_id1 = Number(v.teaminfo_id1);
  if (Number(v.teaminfo_id2) > 0) тіло.teaminfo_id2 = Number(v.teaminfo_id2);
  return тіло;
}

/**
 * Тіло PATCH пари, для кожного боку однаково: вибрана команда — її id; порожньо, а була — явне очищення
 * clear_teaminfo_idN (формат Backend: «не прислав» і далі означає «не чіпати»); порожньо й не було — нічого.
 */
export function тілоЗмінПари(пара, v) {
  const тіло = {};
  for (const с of [1, 2]) {
    const нова = Number(v[`teaminfo_id${с}`]);
    if (нова > 0) тіло[`teaminfo_id${с}`] = нова;
    else if (єКоманда(пара, с)) тіло[`clear_teaminfo_id${с}`] = true;
  }
  return тіло;
}

/**
 * Позиція (1…n у турі), з якою розкладка поставить пару в клітинку `слот` колонки раунду (бриф
 * bracket-slot-position, Богдан 19.11: нова пара має стати саме в натиснуту порожню клітинку).
 * Слот ≠ позиція: позиції йдуть без пропусків, а клітинки, зайняті парами, привʼязаними до наступного
 * раунду, розкладка ставить за командами. Тому перебираємо позиції тією самою розкладкою, що малює дерево.
 * null — жодна позиція не дає цю клітинку (напр. порожні клітинки під останньою парою, коли порядок вирішує
 * місце: пари там завжди йдуть зверху підряд).
 */
export function позиціяДляСлоту(дані, розкласти, параId, раундId, слот) {
  const усі = дані?.bracket || [];
  const тур = усі.filter((п) => п?.tours_id === раундId);
  const пара = тур.find((п) => п.id === параId);
  if (!пара) return null;
  const інші = тур.filter((п) => п.id !== параId);
  for (let поз = 1; поз <= тур.length; поз += 1) {
    const новий = [...інші];
    новий.splice(поз - 1, 0, пара);
    let і = 0;
    const bracket = усі.map((п) => (п?.tours_id === раундId ? новий[і++] : п));
    const р = розкласти({ tours: дані.tours, bracket });
    const колонка = р.колонки.find((к) => к.id === раундId);
    const де = колонка ? колонка.пари.findIndex((п) => п?.id === параId) : р.заТретє?.id === раундId ? 0 : -1;
    if (де === слот) return поз;
  }
  return null;
}
