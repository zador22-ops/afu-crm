// Запуск: npm test (node --test, без залежностей).
//
// Канвасу в Node немає, тож декодування й кодування підміняємо: перевіряємо
// рішення помічника (який розмір, чи перекодовувати, що віддати), а не якість
// JPEG. Справжнє стиснення перевірено в браузері на фото з телефона — див. звіт
// до коміту.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  ФОТО,
  ЛОГО,
  цільовийРозмір,
  вихіднийТип,
  стиснутиФото,
  описСтиснення,
  розмірФайлу,
} from './compressImage.js';

const МБ = 1024 * 1024;

function файл(байт, type = 'image/jpeg', name = 'IMG_0412.jpeg') {
  return new File([new Uint8Array(байт)], name, { type });
}

// Підробка: «декодує» в задані розміри, «кодує» у blob заданої ваги й
// запамʼятовує, з чим її викликали.
function засоби({ ширина, висота, вага = 300 * 1024, падіння } = {}) {
  const виклики = { кодування: [], закрито: 0 };
  return {
    виклики,
    async декодувати() {
      if (падіння === 'декодування') throw new Error('битий файл');
      return { ширина, висота, джерело: 'bitmap', закрити: () => виклики.закрито++ };
    },
    async закодувати(джерело, w, h, тип, якість) {
      if (падіння === 'кодування') throw new Error('toBlob повернув null');
      виклики.кодування.push({ джерело, w, h, тип, якість });
      return new Blob([new Uint8Array(вага)], { type: тип });
    },
  };
}

test('цільовийРозмір: довша сторона стає межею, пропорції зберігаються', () => {
  assert.deepEqual(цільовийРозмір(4032, 3024, 1600), { ширина: 1600, висота: 1200, k: 1600 / 4032 });
  assert.deepEqual(цільовийРозмір(2830, 4164, 1600).висота, 1600);
  assert.equal(цільовийРозмір(2830, 4164, 1600).ширина, 1087);
});

test('цільовийРозмір: не збільшує менше за межу', () => {
  assert.deepEqual(цільовийРозмір(800, 600, 1600), { ширина: 800, висота: 600, k: 1 });
  assert.deepEqual(цільовийРозмір(1600, 1600, 1600), { ширина: 1600, висота: 1600, k: 1 });
});

test('вихіднийТип: PNG лише коли прозорість потрібна і можлива', () => {
  assert.equal(вихіднийТип('image/png', true), 'image/png');
  assert.equal(вихіднийТип('image/webp', true), 'image/png');
  assert.equal(вихіднийТип('image/jpeg', true), 'image/jpeg');
  assert.equal(вихіднийТип('image/png', false), 'image/jpeg');
  assert.equal(вихіднийТип('image/heic', false), 'image/jpeg');
});

test('важке фото з телефона: зменшується до 1600 і стає JPEG 0.85', async () => {
  const з = засоби({ ширина: 4032, висота: 3024, вага: 350 * 1024 });
  const r = await стиснутиФото(файл(7 * МБ), ФОТО, з);
  assert.equal(r.перекодовано, true);
  assert.deepEqual(з.виклики.кодування, [{ джерело: 'bitmap', w: 1600, h: 1200, тип: 'image/jpeg', якість: 0.85 }]);
  assert.equal(r.file.type, 'image/jpeg');
  assert.equal(r.file.name, 'IMG_0412.jpg');
  assert.equal(r.було, 7 * МБ);
  assert.equal(r.стало, 350 * 1024);
  assert.equal(описСтиснення(r), '7,0 МБ → 350 КБ');
});

test('легкий файл у межі: іде як є, без перекодування', async () => {
  const з = засоби({ ширина: 1200, висота: 800 });
  const f = файл(200 * 1024);
  const r = await стиснутиФото(f, ФОТО, з);
  assert.equal(r.file, f);
  assert.equal(r.перекодовано, false);
  assert.equal(з.виклики.кодування.length, 0);
  assert.equal(описСтиснення(r), null);
});

test('у межі за розміром, але важкий: перекодовується без зменшення', async () => {
  const з = засоби({ ширина: 1500, висота: 1000, вага: 400 * 1024 });
  const r = await стиснутиФото(файл(3 * МБ, 'image/png', 'скрін.png'), ФОТО, з);
  assert.equal(r.перекодовано, true);
  assert.deepEqual(з.виклики.кодування[0], { джерело: 'bitmap', w: 1500, h: 1000, тип: 'image/jpeg', якість: 0.85 });
  assert.equal(r.file.name, 'скрін.jpg');
});

test('перекодування того самого розміру вийшло важчим: лишається оригінал', async () => {
  const з = засоби({ ширина: 1500, висота: 1000, вага: 900 * 1024 });
  const f = файл(600 * 1024);
  const r = await стиснутиФото(f, ФОТО, з);
  assert.equal(r.file, f);
  assert.equal(r.перекодовано, false);
});

test('орієнтація: розмір береться з декодованого (уже поверненого) кадру', async () => {
  // Сенсор пише 4032×3024 і кладе в EXIF «повернути на 90°». Декодування з
  // imageOrientation: 'from-image' віддає вже портрет 3024×4032 — і зменшувати
  // треба його, інакше фото ляже боком або сплющиться.
  const з = засоби({ ширина: 3024, висота: 4032 });
  const r = await стиснутиФото(файл(5 * МБ), ФОТО, з);
  assert.equal(r.ширина, 1200);
  assert.equal(r.висота, 1600);
  assert.deepEqual([з.виклики.кодування[0].w, з.виклики.кодування[0].h], [1200, 1600]);
});

test('орієнтація: браузерне декодування просить imageOrientation from-image', async () => {
  // Єдине, що тут можна перевірити без справжнього браузера: з якими опціями
  // викликано createImageBitmap. Кодування падає навмисно — канвасу в Node нема,
  // і помічник має віддати оригінал, а не кинути.
  const було = globalThis.createImageBitmap;
  const опції = [];
  globalThis.createImageBitmap = async (f, o) => {
    опції.push(o);
    return { width: 4032, height: 3024, close() {} };
  };
  try {
    const f = файл(5 * МБ);
    const r = await стиснутиФото(f, ФОТО);
    assert.deepEqual(опції, [{ imageOrientation: 'from-image' }]);
    assert.equal(r.file, f);
  } finally {
    globalThis.createImageBitmap = було;
  }
});

test('логотип з прозорістю: PNG лишається PNG, межа 1000', async () => {
  const з = засоби({ ширина: 3000, висота: 1500, вага: 200 * 1024 });
  const r = await стиснутиФото(файл(4 * МБ, 'image/png', 'partner.png'), ЛОГО, з);
  assert.deepEqual(з.виклики.кодування[0], { джерело: 'bitmap', w: 1000, h: 500, тип: 'image/png', якість: 0.85 });
  assert.equal(r.file.type, 'image/png');
  assert.equal(r.file.name, 'partner.png');
});

test('SVG, GIF і не-зображення не чіпаються взагалі', async () => {
  for (const type of ['image/svg+xml', 'image/gif', 'application/pdf']) {
    const з = засоби({ ширина: 5000, висота: 5000 });
    const f = файл(5 * МБ, type, 'x');
    const r = await стиснутиФото(f, ФОТО, з);
    assert.equal(r.file, f, type);
    assert.equal(з.виклики.кодування.length, 0, type);
  }
});

test('збій декодування чи кодування: віддається оригінал, а не помилка', async () => {
  for (const падіння of ['декодування', 'кодування']) {
    const f = файл(8 * МБ);
    const r = await стиснутиФото(f, ФОТО, засоби({ ширина: 4000, висота: 3000, падіння }));
    assert.equal(r.file, f, падіння);
    assert.equal(r.перекодовано, false, падіння);
  }
});

test('декодований кадр звільняється в кожній гілці', async () => {
  const легкий = засоби({ ширина: 800, висота: 600 });
  await стиснутиФото(файл(100 * 1024), ФОТО, легкий);
  const важкий = засоби({ ширина: 4000, висота: 3000 });
  await стиснутиФото(файл(6 * МБ), ФОТО, важкий);
  const збій = засоби({ ширина: 4000, висота: 3000, падіння: 'кодування' });
  await стиснутиФото(файл(6 * МБ), ФОТО, збій);
  assert.deepEqual([легкий.виклики.закрито, важкий.виклики.закрито, збій.виклики.закрито], [1, 1, 1]);
});

test('розмірФайлу', () => {
  assert.equal(розмірФайлу(10 * МБ), '10,0 МБ');
  assert.equal(розмірФайлу(1.5 * МБ), '1,5 МБ');
  assert.equal(розмірФайлу(358_000), '350 КБ');
  assert.equal(розмірФайлу(10), '1 КБ');
});
