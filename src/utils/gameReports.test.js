import { test } from 'node:test';
import assert from 'node:assert/strict';
import { ДО_СКАРГ, ОНОВЛЮВАТИ_КОЖНІ, кількістьСкарг, можнаПитати, повторСкарг, скаргиСловами } from './gameReports.js';

test('питаємо раз на 5 хв, поки сервер не сказав «нема права»', () => {
  assert.equal(ОНОВЛЮВАТИ_КОЖНІ, 300_000);
  assert.equal(можнаПитати(null), true);
  assert.equal(можнаПитати({ status: 500 }), true); // збій мережі чи сервера — пробуємо далі
  assert.equal(можнаПитати({ status: 401 }), true); // 401 розлогінює вся CRM, не тут
  assert.equal(можнаПитати({ status: 403 }), false);
});

test('повтор: один раз після збою, після 403 — ні', () => {
  assert.equal(повторСкарг(0, { status: 500 }), true);
  assert.equal(повторСкарг(1, { status: 500 }), false);
  assert.equal(повторСкарг(0, { status: 403 }), false);
});

test('кількість: довжина черги, а все інше — нуль, тобто нічого не показувати', () => {
  assert.equal(кількістьСкарг([{ id: 1 }, { id: 2 }, { id: 3 }]), 3);
  assert.equal(кількістьСкарг([]), 0);
  assert.equal(кількістьСкарг(undefined), 0);
  assert.equal(кількістьСкарг({ message: 'Доступ заборонено' }), 0);
});

test('скаргиСловами: відмінювання', () => {
  const очікуване = {
    1: '1 нерозглянута скарга',
    2: '2 нерозглянуті скарги',
    4: '4 нерозглянуті скарги',
    5: '5 нерозглянутих скарг',
    11: '11 нерозглянутих скарг',
    12: '12 нерозглянутих скарг',
    14: '14 нерозглянутих скарг',
    21: '21 нерозглянута скарга',
    22: '22 нерозглянуті скарги',
    111: '111 нерозглянутих скарг',
    112: '112 нерозглянутих скарг',
    122: '122 нерозглянуті скарги',
  };
  for (const [n, s] of Object.entries(очікуване)) assert.equal(скаргиСловами(Number(n)), s);
});

test('клік веде на вкладку «Скарги» сторінки гри', () => {
  const u = new URL(ДО_СКАРГ, 'http://x');
  assert.equal(u.pathname, '/game');
  assert.equal(u.searchParams.get('tab'), 'reports');
});
