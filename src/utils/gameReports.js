// Скарги на ніки гри: скільки їх чекає модератора (бриф vluch-push-moderation, пункт Г).
//
// ЧОМУ БЕЗ ОКРЕМОГО ЕНДПОІНТА-ЛІЧИЛЬНИКА. «Розглянуто» в CRM видаляє рядок
// game_report (game-admin/reports/{id} DELETE), тож game-admin/reports — це і є
// черга нерозглянутих, і її довжина — шукане число. Той самий ключ кеша і той
// самий фетчер, що й у вкладці «Скарги» сторінки гри: натиснули «Розглянуто» —
// лічильник у меню зменшився відразу, без окремого запиту.
//
// ЧОМУ 403 — ЦЕ «НЕ ПОКАЗУВАТИ», А НЕ ПОМИЛКА. Право 20 перевіряє сервер (Check
// access rights); у самій CRM списку прав користувача немає. Роль без права
// отримує 403 — лічильника в неї нема, і питати далі сенсу нема: ні за
// інтервалом, ні при поверненні на вкладку, ні при монтуванні. Останнє не
// очевидне: react-query повторює запит, що впав, щойно монтується новий
// спостерігач, тож без вимкнення роль без права слала б 403 на кожен перехід
// на головну (звірено в браузері 16.10).

export const КЛЮЧ_СКАРГ = ['game-reports'];
export const ШЛЯХ_СКАРГ = '/game-admin/reports';
export const ОНОВЛЮВАТИ_КОЖНІ = 5 * 60_000;

const безПрава = (помилка) => помилка?.status === 403;

/** Чи питати сервер узагалі: так, поки він не відповів «нема права» (403). */
export function можнаПитати(помилка) {
  return !безПрава(помилка);
}

/** Повтор після збою: один раз, як у всій CRM, але не після 403. */
export function повторСкарг(спроба, помилка) {
  return !безПрава(помилка) && спроба < 1;
}

/** Довжина черги; будь-що, крім масиву (помилка, ще не завантажено), — 0. */
export function кількістьСкарг(дані) {
  return Array.isArray(дані) ? дані.length : 0;
}

/** 1 нерозглянута скарга, 2 нерозглянуті скарги, 5 нерозглянутих скарг. */
export function скаргиСловами(n) {
  const д = n % 10;
  const с = n % 100;
  if (д === 1 && с !== 11) return `${n} нерозглянута скарга`;
  if (д >= 2 && д <= 4 && (с < 12 || с > 14)) return `${n} нерозглянуті скарги`;
  return `${n} нерозглянутих скарг`;
}

/** Куди веде клік: сторінка гри, вкладка «Скарги». */
export const ДО_СКАРГ = '/game?tab=reports';
